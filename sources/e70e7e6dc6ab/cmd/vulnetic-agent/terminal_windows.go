func run() error {
	showVersion := flag.Bool("version", false, "print product and version without connecting")
	about := flag.Bool("about", false, "explain temporary terminal access without making changes")
	connect := flag.Bool("connect", false, "explicitly authorize foreground remote execution until the original deadline")
	server := flag.String("server", "", "Vulnetic HTTPS URL")
	enrollment := flag.String("enrollment-file", "", "private one-use enrollment input, removed before connecting")
	directory := flag.String("directory", "", "existing private task workspace")
	lifetime := flag.Int("lease-seconds", 0, "maximum foreground lifetime; never extends the server deadline")
	flag.Parse()
	if *showVersion {
		fmt.Printf("%s %s\n", agentidentity.Windows().ProductName, windowsVersion())
		return nil
	}
	if *about {
		describeWindowsExecutor(os.Stdout)
		return nil
	}
	if !*connect {
		return errors.New("review -about, then use the foreground connection command generated by Vulnetic; service installation is not supported")
	}
	ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer cancel()
	return runWindowsTerminal(ctx, *server, *enrollment, *directory, *lifetime, os.Stdout)
}

func requireWindowsTerminalUser() error {
	token := windows.GetCurrentProcessToken()
	if token.IsElevated() {
		return errors.New("close this elevated terminal and run Vulnetic from a non-administrator PowerShell window")
	}
	groups, err := token.GetTokenGroups()
	if err != nil {
		return err
	}
	for _, group := range groups.AllGroups() {
		if group.Attributes&windows.SE_GROUP_ENABLED == 0 || group.Attributes&windows.SE_GROUP_USE_FOR_DENY_ONLY != 0 {
			continue
		}
		switch group.Sid.String() {
		case "S-1-5-18", "S-1-5-32-544", "S-1-5-32-547", "S-1-5-32-548", "S-1-5-32-549", "S-1-5-32-550", "S-1-5-32-551":
			return errors.New("foreground execution requires a user without active privileged groups")
		}
	}
	var size uint32
	_ = windows.GetTokenInformation(token, windows.TokenPrivileges, nil, 0, &size)
	if size == 0 || size > 65536 {
		return errors.New("could not inspect terminal privileges")
	}
	buffer := make([]byte, size)
	if err = windows.GetTokenInformation(token, windows.TokenPrivileges, &buffer[0], size, &size); err != nil {
		return err
	}
	allowed := make(map[windows.LUID]bool)
	for _, name := range []string{"SeChangeNotifyPrivilege", "SeShutdownPrivilege", "SeUndockPrivilege", "SeIncreaseWorkingSetPrivilege", "SeTimeZonePrivilege"} {
		value, _ := windows.UTF16PtrFromString(name)
		var id windows.LUID
		if err = windows.LookupPrivilegeValue(nil, value, &id); err != nil {
			return err
		}
		allowed[id] = true
	}
	for _, privilege := range (*windows.Tokenprivileges)(unsafe.Pointer(&buffer[0])).AllPrivileges() {
		if !allowed[privilege.Luid] {
			return errors.New("the terminal retains a privileged Windows right; use a restricted account")
		}
	}
	return nil
}

func runWindowsTerminal(ctx context.Context, server, enrollment, directory string, lifetime int, out io.Writer) error {
	if err := requireWindowsTerminalUser(); err != nil {
		return err
	}
	base, err := reverseagent.ValidateServerURL(server)
	if err != nil {
		return err
	}
	if lifetime < 300 || lifetime > 604800 {
		return errors.New("invalid foreground lifetime")
	}
	if !filepath.IsAbs(directory) || filepath.Clean(directory) == filepath.VolumeName(directory)+string(filepath.Separator) {
		return errors.New("an existing private workspace is required")
	}
	info, err := os.Stat(directory)
	if err != nil || !info.IsDir() {
		return errors.New("workspace must be an existing directory")
	}
	if err = winsecure.Private(directory); err != nil {
		return fmt.Errorf("workspace is not private: %w", err)
	}
	if filepath.Base(enrollment) != "enrollment" {
		return errors.New("use the generated private enrollment file")
	}
	if err = winsecure.Private(enrollment); err != nil {
		return err
	}
	file, err := os.Open(enrollment)
	if err != nil {
		return err
	}
	data, readErr := io.ReadAll(io.LimitReader(file, 257))
	closeErr := file.Close()
	if readErr != nil || closeErr != nil || len(data) > 256 {
		return errors.New("could not read the bounded enrollment input")
	}
	join := strings.TrimSpace(string(data))
	token, err := base64.RawURLEncoding.DecodeString(join)
	if err != nil || len(token) != 32 {
		return errors.New("invalid one-use enrollment token")
	}
	if err = os.Remove(enrollment); err != nil {
		return errors.New("could not remove the private enrollment input; no connection started")
	}
	describeWindowsExecutor(out)
	fmt.Fprintf(out, "Connecting to %s. Workspace: %s\nKeep this terminal open. Press Ctrl+C to stop.\n", base.String(), directory)
	lease, cancel := context.WithTimeout(ctx, time.Duration(lifetime)*time.Second)
	defer cancel()
	err = reverseagent.Run(lease, reverseagent.ClientConfig{
		ServerURL: base.String(), EnrollmentToken: join, Username: "vulnetic-terminal", Directory: filepath.Clean(directory),
		OnLease: func(deadline time.Time) {
			fmt.Fprintf(out, "Access deadline: %s UTC. Reconnection does not renew it.\n", deadline.UTC().Format(time.RFC3339))
		},
	})
	if errors.Is(err, reverseagent.ErrLeaseEnded) || errors.Is(err, context.DeadlineExceeded) {
		fmt.Fprintln(out, "Access expired or was revoked. Remote execution stopped; workspace files are preserved.")
		return nil
	}
	if ctx.Err() != nil {
		fmt.Fprintln(out, "Terminal connection closed. Remote execution stopped; workspace files are preserved.")
		return nil
	}
	return err
}
